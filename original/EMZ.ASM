SETUP	PROC		; Cargar programa con FCB1 y FCB2 y command tail
	MOV	CL,0Fh
	MOV	DX,5Ch
	CALL	CPM			; Open File

	MOV	DX,80h
L03A0:	ADD	DX,80h
	PUSH	DX
	MOV	CL,1Ah
	CALL	CPM			; Set File Buffer Address

	MOV	CL,14h
	MOV	DX,5Ch
	CALL	CPM			; Sequential Read
	POP	DX
	OR	AL,AL
	JZ	L03A0

	MOV	CL,10h
	MOV	DX,5Ch
	CALL	CPM			; Close Output File

	MOV	DI,0			; Borrar Low Storage Map (0-100h)
	MOV	CX,80h
	XOR	AX,AX
	REPZ	STOSW

	MOV	SI,81h
	MOV	DI,5Ch
	MOV	AX,2901h
	INT	21h			; Parse filename para despreciar FCB

	PUSH	SI

	MOV	DI,5Ch
	INT	21h			; Parse filename para crear FCB1

	MOV	DI,6Ch
	INT	21h			; Parse filename para crear FCB2

	POP	SI

	MOV	DI,81h
L03E1:	LODSB				; Copiar command tail
	CMP	AL,0Dh
	JZ	L03EF
	STOSB
	INC	BYTE PTR ES:[0080H]
	JMP	L03E1

L03EF:	MOV	CL,1Ah
	MOV	DX,80h
	CALL	CPM			; Set File Buffer Address
	RET
SETUP	ENDP

ClearREGs	PROC
	MOV	AX,0
	MOV	BX,AX
	MOV	CX,AX
	MOV	DX,AX
	MOV	BP,AX
	MOV	SI,0EBA9h
	MOV	WORD PTR [SI],0
	MOV	WORD PTR DS:[004CH],AX
	MOV	WORD PTR DS:[004EH],AX
	MOV	WORD PTR DS:[0050H],AX
	MOV	WORD PTR DS:[0052H],AX
	MOV	WORD PTR DS:[0054H],AX
	MOV	WORD PTR DS:[0056H],AX
	MOV	BYTE PTR DS:[0058H],AL
	MOV	BYTE PTR DS:[0059H],AL
	MOV	DI,100h				; PC = 100h
	RET
ClearREGs	ENDP

SETLowMap	PROC
	MOV	AL,0C3h
	MOV	BYTE PTR DS:[0000H],AL		; RST 0
	MOV	BYTE PTR DS:[0005H],AL		; JMP
	MOV	CX,0FA03h
	MOV	WORD PTR DS:[0001H],CX		; BIOS Address Entry Point
	MOV	CX,0EC06h
	MOV	WORD PTR DS:[0006H],CX		; BDOS Address Entry Point
	MOV	AL,0
	MOV	BYTE PTR DS:[0003H],AL		; IOBYTE
	MOV	AH,19h
	INT	21h				; Get Current Disk
	MOV	BYTE PTR DS:[0004H],AL		; Default Drive
	MOV	AX,0
	MOV	BYTE PTR DS:[0042H],AL
	MOV	WORD PTR DS:[0043H],AX
	MOV	WORD PTR DS:[0045H],AX		;
	MOV	BYTE PTR DS:[0047H],AL		; BIOS Work Area
	MOV	WORD PTR DS:[0048H],AX		;
	MOV	WORD PTR DS:[004AH],AX
	MOV	WORD PTR DS:[0040H],AX
	MOV	WORD PTR DS:[003CH],80h		; RST 7 ???
	RET
SETLowMap	ENDP

