REG_EMULADOR    PROC
	MOV	AX,REGIST_AF
	MOV	BX,REGIST_HL
	MOV	DX,REGIST_BC
	MOV	BP,REGIST_DE
	MOV	SI,REGIST_sp8
	MOV	DI,REGIST_PC
	RET
REG_EMULADOR	ENDP

EMULADOR_REG	PROC
	MOV	REGIST_AF,AX
	MOV	REGIST_HL,BX
	MOV	REGIST_BC,DX
	MOV	REGIST_DE,BP
	MOV	REGIST_sp8,SI
	MOV	REGIST_PC,DI
	RET
EMULADOR_REG	ENDP

