BREAKP	PROC
        PUSHF
	PUSH	AX
	MOV	AH,1
	INT	16H
;	CMP	ES:BREAK,00
	JZ	RETOR
	mov	ah,0
	INT	16H
	CMP	AL,3  		; VER SI ES ^C
	JNE	RETOR
	INT	23H
	POP	AX
	POPF
	INC	SP
	INC	SP
	JMP	HALT
RETOR:	POP	AX
	POPF
	RET	
